#!/usr/bin/env node
/*
 * Marvel Nums organizer.
 * Put this file in the folder that holds all the flat files (next to server.js), then run:
 *     node organize.js            -> arranges folders, then commits and pushes to GitHub main (goes live on Render)
 *     node organize.js --no-push  -> arranges folders only
 */
const fs = require('fs');
const path = require('path');
const { execSync } = require('child_process');

const ROOT = process.cwd();
const NO_PUSH = process.argv.includes('--no-push');
const SELF = path.basename(__filename);

// Server-side modules (required by server.js as ./lib/xxx)
const LIB = new Set([
  'boost2.js', 'brand-logos.js', 'campaigns.js', 'countries.js', 'countries.data.json',
  'engagement.js', 'extras.js', 'flw-methods.js', 'fx.js', 'geo.js', 'global-payments.js', 'mailer.js',
  'marvel-upgrade.js', 'minipdf.js', 'mysql.js', 'opaque-ref.js',
  'otp-suite.js', 'platform.js', 'restock-notify.js', 'settings.js', 'tutorials.js', 'welcomepopup.js',
]);
// Files that share a name with a browser file: the "(1)" copy is the server one
const LIB_DUP = new Set(['boost (1).js', 'market2 (1).js', 'market3 (1).js', 'market4 (1).js']);
// Stay in the project root
const ROOT_FILES = new Set(['server.js', 'site.config.js', 'package.json', 'package-lock.json', 'README.md', '.gitignore', '.env']);
// Browser files that live directly in public/
const PUBLIC_ROOT = new Set(['theme.css', 'style.css', 'script.js', 'welcome-popup.js', 'manifest.json', 'robots.txt',
  'market2.js', 'market3.js', 'market4.js', 'marketplace.js', 'tools.js', 'game.js']);

function destFor(name) {
  if (name === SELF || ROOT_FILES.has(name)) return null;
  if (/^gitkeep( \(\d+\))?$/i.test(name) || name === '.gitkeep') return 'SKIP';
  // already in the flat pattern: public__js__name.js -> public/js/name.js
  if (name.includes('__')) return name.split('__').join('/');
  if (LIB_DUP.has(name)) return 'lib/' + name.replace(' (1)', '');
  if (LIB.has(name)) return 'lib/' + name;
  if (PUBLIC_ROOT.has(name)) return 'public/' + name;
  const ext = path.extname(name).toLowerCase();
  if (ext === '.html') return 'public/' + name;
  if (ext === '.css') return 'public/css/' + name;
  if (ext === '.js') return 'public/js/' + name;
  if (ext === '.png' || ext === '.ico' || ext === '.svg' || ext === '.jpg' || ext === '.webp') return 'public/' + name;
  return null;
}

function move(from, to) {
  fs.mkdirSync(path.dirname(to), { recursive: true });
  try { fs.renameSync(from, to); } catch (e) { fs.copyFileSync(from, to); fs.unlinkSync(from); }
}

if (!fs.existsSync(path.join(ROOT, 'server.js'))) {
  console.error('server.js not found here. Put organize.js in the same folder as server.js and run again.');
  process.exit(1);
}

let moved = 0; const left = [];
for (const ent of fs.readdirSync(ROOT, { withFileTypes: true })) {
  if (!ent.isFile()) continue;
  const d = destFor(ent.name);
  if (d === 'SKIP') { fs.unlinkSync(path.join(ROOT, ent.name)); continue; }
  if (!d) { if (!ROOT_FILES.has(ent.name) && ent.name !== SELF) left.push(ent.name); continue; }
  move(path.join(ROOT, ent.name), path.join(ROOT, d));
  moved++;
}

// home.html loads the icon from /img/
const icon = path.join(ROOT, 'public/marvel-icon-192.png');
if (fs.existsSync(icon)) { fs.mkdirSync(path.join(ROOT, 'public/img'), { recursive: true }); fs.copyFileSync(icon, path.join(ROOT, 'public/img/marvel-icon-192.png')); }

// folders the server writes into
for (const dir of ['public/uploads', 'public/receipts', 'public/files', 'public/js', 'public/css', 'lib']) {
  fs.mkdirSync(path.join(ROOT, dir), { recursive: true });
}
for (const dir of ['public/uploads', 'public/receipts', 'public/files']) {
  const k = path.join(ROOT, dir, '.gitkeep');
  if (!fs.existsSync(k)) fs.writeFileSync(k, '');
}
const gi = path.join(ROOT, '.gitignore');
if (!fs.existsSync(gi)) fs.writeFileSync(gi, 'node_modules/\n.env\n.DS_Store\n');

console.log(`Moved ${moved} files into place.`);
if (left.length) console.log('Left untouched (unknown type): ' + left.join(', '));

// Check every local asset the pages point to
const pub = path.join(ROOT, 'public');
const missing = new Set();
for (const f of fs.readdirSync(pub).filter(f => f.endsWith('.html'))) {
  const html = fs.readFileSync(path.join(pub, f), 'utf8');
  for (const m of html.matchAll(/(?:src|href)="([^"#?]+\.(?:js|css|png|json))(?:\?[^"]*)?"/g)) {
    const u = m[1];
    if (/^(https?:)?\/\//.test(u) || u === '/brand.css') continue; // /brand.css is generated by server.js
    const p = u.startsWith('/') ? path.join(pub, u) : path.join(pub, u);
    if (!fs.existsSync(p)) missing.add(u + '  (used in ' + f + ')');
  }
}
if (missing.size) {
  console.log('\nHeads up: pages reference these files, but they are not in your upload:');
  [...missing].sort().forEach(m => console.log('  ' + m));
  console.log('(These were already missing from the zip. Add them if the site needs them.)');
}

if (NO_PUSH) { console.log('\nDone (no push).'); process.exit(0); }

try {
  execSync('git rev-parse --is-inside-work-tree', { stdio: 'ignore' });
} catch (e) {
  console.log('\nNot a git repo, so nothing was pushed. Files are arranged.');
  process.exit(0);
}
try {
  execSync('git add -A', { stdio: 'inherit' });
  try { execSync('git commit -m "Arrange files into lib/ and public/ structure"', { stdio: 'inherit' }); }
  catch (e) { console.log('Nothing new to commit.'); }
  execSync('git push origin HEAD:main', { stdio: 'inherit' });
  console.log('\nPushed to main. Render will deploy it now.');
} catch (e) {
  console.log('\nFiles are arranged, but the push failed. Run: git push origin HEAD:main');
}
